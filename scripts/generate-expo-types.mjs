import { readFile, unlink } from "node:fs/promises";
import { createRequire } from "node:module";
import path from "node:path";

const projectRoot = path.resolve(process.argv[2] ?? process.cwd());
const requireFromProject = createRequire(path.join(projectRoot, "package.json"));
const expoDirectory = path.dirname(
  requireFromProject.resolve("expo/package.json")
);
const generator = requireFromProject(
  path.join(
    expoDirectory,
    "../@expo/cli/build/src/start/server/type-generation/startTypescriptTypeGeneration"
  )
);

await generator.startTypescriptTypeGenerationAsync({ projectRoot });

const generatedGitignorePath = path.join(projectRoot, ".gitignore");
try {
  const generatedGitignore = await readFile(generatedGitignorePath, "utf8");
  const lines = generatedGitignore
    .split(/\r?\n/)
    .map((line) => line.trim())
    .filter(Boolean);
  const containsOnlyExpoTypegenIgnore =
    lines.length === 4 &&
    lines[0]?.startsWith("# @generated expo-cli sync-") &&
    lines[1] === "# The following patterns were generated by expo-cli" &&
    lines[2] === "expo-env.d.ts" &&
    lines[3] === "# @end expo-cli";
  if (containsOnlyExpoTypegenIgnore) {
    await unlink(generatedGitignorePath);
  }
} catch (error) {
  if (!(error instanceof Error && "code" in error && error.code === "ENOENT")) {
    throw error;
  }
}
